test('personal edits update the map, survive reload, and can be restored', async ({ page }) => {
  await page.route('**/data/resorts.json*', route => route.fulfill({ contentType: 'application/javascript', body: `export default ${JSON.stringify(fixture)};` }));
  await page.goto('/');
  await page.getByRole('button', { name: '⚙ Settings' }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await expect(dialog).toContainText('only in this browser');
  const alpine = dialog.locator('.edit-row').filter({ hasText: 'Test Alpine' });
  await alpine.locator('.edit-value').fill('120000');
  await alpine.locator('.edit-period').fill('2024–25');
  await dialog.getByRole('button', { name: 'Save edits' }).click();
  await expect(dialog.getByRole('status')).toContainText('Saved 1 resort');
  await dialog.getByRole('button', { name: 'Close settings' }).click();
  await expect(page.locator('#heat-status')).toContainText('1 of 3 resorts have data');
  await expect(page.locator('path.leaflet-interactive').first()).toHaveAttribute('fill', '#dbe46b');
  await page.reload();
  await expect(page.locator('#heat-status')).toContainText('1 of 3 resorts have data');
  await page.locator('path.leaflet-interactive').first().click();
  await expect(page.locator('#detail')).toContainText('120,000');
  await expect(page.locator('#detail')).toContainText('personal edit');
  await page.getByRole('button', { name: '⚙ Settings' }).click();
  const row = dialog.locator('.edit-row').filter({ hasText: 'Test Alpine' });
  await row.locator('.edit-check').check();
  page.once('dialog', alert => alert.accept());
  await dialog.getByRole('button', { name: 'Restore selected' }).click();
  await expect(dialog.getByRole('status')).toContainText('Restored 1 resort');
  await dialog.getByRole('button', { name: 'Close settings' }).click();
  await expect(page.locator('#heat-status')).toHaveText('No annual visits data for these resorts');
});
